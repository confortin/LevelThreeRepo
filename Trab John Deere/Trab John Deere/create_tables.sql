
-- PREDICTING MANUFACTURING DEFECTS
-- PostgreSQL

-- 1. PRODUCTION
CREATE TABLE Production (
    ProductionID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ProductionVolume INTEGER NOT NULL,
    ProductionCost DOUBLE PRECISION NOT NULL,
    WorkerProductivity DOUBLE PRECISION NOT NULL,
    SafetyIncidents INTEGER NOT NULL
);

-- 2. SUPPLIER
CREATE TABLE Supplier (
    SupplierID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ProductionID INTEGER NOT NULL UNIQUE,
    SupplierQuality DOUBLE PRECISION NOT NULL,
    DeliveryDelay INTEGER NOT NULL,
    InventoryTurnover DOUBLE PRECISION NOT NULL,
    StockoutRate DOUBLE PRECISION NOT NULL,

    CONSTRAINT fk_supplier_production
        FOREIGN KEY (ProductionID)
        REFERENCES Production(ProductionID)
);

-- 3. PERFORMANCE
CREATE TABLE Performance (
    PerformanceID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ProductionID INTEGER NOT NULL UNIQUE,
    MaintenanceHours INTEGER NOT NULL,
    DowntimePercentage DOUBLE PRECISION NOT NULL,
    EnergyConsumption DOUBLE PRECISION NOT NULL,
    EnergyEfficiency DOUBLE PRECISION NOT NULL,
    AdditiveProcessTime DOUBLE PRECISION NOT NULL,
    AdditiveMaterialCost DOUBLE PRECISION NOT NULL,

    CONSTRAINT fk_performance_production
        FOREIGN KEY (ProductionID)
        REFERENCES Production(ProductionID)
);

-- 4. QUALITY
CREATE TABLE Quality (
    QualityID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ProductionID INTEGER NOT NULL UNIQUE,
    DefectRate DOUBLE PRECISION NOT NULL,
    QualityScore DOUBLE PRECISION NOT NULL,
    DefectStatus INTEGER NOT NULL,

    CONSTRAINT fk_quality_production
        FOREIGN KEY (ProductionID)
        REFERENCES Production(ProductionID),

    CONSTRAINT chk_defect_status
        CHECK (DefectStatus IN (0, 1))
);
